create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  role text not null check (role in ('lecturer', 'student')),
  created_at timestamptz not null default now()
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  lecturer_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  description text not null,
  content text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null,
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now(),
  constraint messages_sender_id_fkey
    foreign key (sender_id) references public.profiles (id) on delete cascade
);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), 'Pengguna'),
    case
      when new.raw_user_meta_data ->> 'role' = 'lecturer' then 'lecturer'
      else 'student'
    end
  );
  return new;
end;
$$;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup
after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

update public.profiles as profile
set name = nullif(auth_user.raw_user_meta_data ->> 'name', '')
from auth.users as auth_user
where auth_user.id = profile.id
  and profile.name = 'Pengguna'
  and nullif(auth_user.raw_user_meta_data ->> 'name', '') is not null;

create or replace function public.update_my_profile_name(new_name text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_name text := nullif(btrim(new_name), '');
begin
  if auth.uid() is null then
    raise exception 'Login required';
  end if;
  if normalized_name is null or char_length(normalized_name) > 80 then
    raise exception 'Name must be between 1 and 80 characters';
  end if;

  update public.profiles
  set name = normalized_name
  where id = (select auth.uid());
  if not found then
    raise exception 'Profile not found';
  end if;
end;
$$;

revoke all on function public.update_my_profile_name(text) from public, anon;
grant execute on function public.update_my_profile_name(text) to authenticated;

alter table public.profiles enable row level security;
alter table public.materials enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Authenticated users can read profiles" on public.profiles;
create policy "Authenticated users can read profiles"
on public.profiles for select to authenticated
using (true);

drop policy if exists "Authenticated users can read materials" on public.materials;
create policy "Authenticated users can read materials"
on public.materials for select to authenticated
using (true);

drop policy if exists "Lecturers can add their own materials" on public.materials;
create policy "Lecturers can add their own materials"
on public.materials for insert to authenticated
with check (
  lecturer_id = (select auth.uid())
  and exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'lecturer'
  )
);

drop policy if exists "Lecturers can update their own materials" on public.materials;
create policy "Lecturers can update their own materials"
on public.materials for update to authenticated
using (
  lecturer_id = (select auth.uid())
  and exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'lecturer'
  )
)
with check (
  lecturer_id = (select auth.uid())
  and exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'lecturer'
  )
);

drop policy if exists "Lecturers can delete their own materials" on public.materials;
create policy "Lecturers can delete their own materials"
on public.materials for delete to authenticated
using (
  lecturer_id = (select auth.uid())
  and exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'lecturer'
  )
);

drop policy if exists "Authenticated users can read messages" on public.messages;
create policy "Authenticated users can read messages"
on public.messages for select to authenticated
using (true);

drop policy if exists "Users can send messages as themselves" on public.messages;
create policy "Users can send messages as themselves"
on public.messages for insert to authenticated
with check (sender_id = (select auth.uid()));

grant usage on schema public to authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.materials to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.materials_id_seq to authenticated;
